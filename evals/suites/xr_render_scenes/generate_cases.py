"""Write ``cases/scenarios.yaml`` from the original corpus (``xr_render_demo_eval.cases.CASES``).

The corpus stays in Python (its predicates are callables), so each YAML case names its corpus entry and the driver
and scorer look it up. Run ``python generate_cases.py`` after the corpus changes; a test fails when the file is stale.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent


def render() -> str:
    spec = importlib.util.spec_from_file_location("xr_render_scenes_drivers", HERE / "drivers.py")
    drivers = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(drivers)
    cases = [
        {
            "id": case["name"],
            "input": {"text": case["user"], "driver": "../drivers.py:scene_turn", "params": {"case": case["name"]}},
            "scorer": {"type": "python", "function": "../scorers.py:scenario"},
            "tags": ["scenario", case["name"].split("_")[0]],
        }
        for case in drivers.harness().CORPUS_CASES
    ]
    document = {
        "suite": "xr_render_scenes",
        "version": 1,
        "description": "xr-render scene supervisor: spoken requests against an in-memory scene (original corpus)",
        "defaults": {"role": "answer", "pass_threshold": 1.0},
        "cases": cases,
    }
    header = (
        "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
        "# SPDX-License-Identifier: Apache-2.0\n\n"
        "# Generated by generate_cases.py from xr_render_demo_eval/cases.py (agent-samples/xr-render-demo/eval). "
        "Do not edit.\n"
    )
    return header + yaml.safe_dump(document, sort_keys=False, width=120, allow_unicode=True)


if __name__ == "__main__":
    (HERE / "cases" / "scenarios.yaml").write_text(render(), encoding="utf-8")
    sys.stdout.write("wrote cases/scenarios.yaml\n")
